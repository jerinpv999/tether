'use strict';
/*
 * Workflow child process. One per running workflow instance; stays alive until
 * the workflow ends. Talks to its worker over a gRPC bidi stream; the worker
 * relays everything to the leader master.
 */
const crypto = require('crypto');
const C = require('../grpc/common');
const { Engine } = require('./engine');

const ADDR = process.env.FLOWFORGE_GRPC;
const INSTANCE = process.env.FLOWFORGE_INSTANCE;
const TOKEN = process.env.FLOWFORGE_TOKEN;
if (!ADDR || !INSTANCE || !TOKEN) { console.error('child: missing FLOWFORGE_* env'); process.exit(2); }

const pkg = C.loadProto();
// The worker hosting this process listens on loopback; we authenticate with
// Basic credentials instanceId:token (token generated by the worker per child).
const client = new pkg.Orchestrator(ADDR, C.grpc.credentials.createInsecure(), C.CHANNEL_OPTS);
const call = client.Connect(C.authMetadata(INSTANCE, TOKEN));

let engine = null;
let ending = false;
const pending = new Map();  // request_id -> {resolve, reject}
const eventHandlers = new Map(); // subscription_id -> fn

const send = (body) => { if (!ending || body.status) { try { call.write({ instance_id: INSTANCE, token: TOKEN, ...body }); } catch {} } };

const bridge = {
  status: (s) => send({ status: s }),
  activity: (a) => send({ activity: a }),
  log: (level, message, nodeId, data) => send({ log: { level, message, node_id: nodeId || '', data_json: data === undefined ? '' : JSON.stringify(data) } }),
  response: (r) => send({ response: r }),
  request: (op, payload) => new Promise((resolve, reject) => {
    const id = crypto.randomUUID();
    pending.set(id, { resolve, reject });
    send({ request: { request_id: id, op, payload_json: JSON.stringify(payload ?? {}) } });
  }),
  onEvent: (subId, fn) => eventHandlers.set(subId, fn),
  offEvent: (subId) => eventHandlers.delete(subId),
};

function exit(code) {
  ending = true;
  clearInterval(beat);
  try { call.end(); } catch {}
  setTimeout(() => process.exit(code), 100).unref();
}

call.on('data', async (msg) => {
  switch (msg.body) {
    case 'start': {
      if (engine) return;
      const definition = JSON.parse(msg.start.definition_json);
      const input = msg.start.input_json ? JSON.parse(msg.start.input_json) : {};
      const meta = JSON.parse(msg.start.meta_json || '{}');
      engine = new Engine({ definition, input, meta, bridge });
      const result = await engine.run();
      await engine.drain();
      bridge.log(result.status === 'COMPLETED' ? 'info' : 'warn', `workflow ${result.status}${result.error ? ': ' + result.error : ''}`);
      send({ status: { status: result.status, output_json: JSON.stringify(result.output ?? null), error: result.error || '', context_json: JSON.stringify(result.vars || {}), current_nodes: [] } });
      for (const p of pending.values()) p.reject(Object.assign(new Error('workflow finished'), { aborted: true }));
      exit(0);
      break;
    }
    case 'control':
      if (engine) engine.control(msg.control);
      break;
    case 'reply': {
      const p = pending.get(msg.reply.request_id);
      if (!p) return;
      pending.delete(msg.reply.request_id);
      const result = msg.reply.result_json ? JSON.parse(msg.reply.result_json) : null;
      if (msg.reply.ok) p.resolve(result);
      else p.reject(Object.assign(new Error(msg.reply.error || 'request failed'), { result }));
      break;
    }
    case 'event': {
      const fn = eventHandlers.get(msg.event.subscription_id);
      if (fn) fn(msg.event.payload_json ? JSON.parse(msg.event.payload_json) : null, { source: msg.event.source, topic: msg.event.topic });
      break;
    }
    default: break;
  }
});

call.on('error', (e) => { if (!ending) { console.error(`[child ${INSTANCE}] gRPC error: ${e.message}`); process.exit(3); } });
call.on('end', () => { if (!ending) process.exit(3); });

// Die with the master: the IPC channel closes when the parent goes away, and as a
// fallback we notice being re-parented (orphaned) within a second.
process.on('disconnect', () => process.exit(4));
const parentPid = process.ppid;
setInterval(() => { if (process.ppid !== parentPid) process.exit(4); }, 1000).unref();
process.on('uncaughtException', (e) => {
  try { send({ status: { status: 'FAILED', error: `uncaught: ${e.message}`, output_json: '', context_json: '', current_nodes: [] } }); } catch {}
  exit(1);
});
process.on('unhandledRejection', (e) => bridge.log('error', `unhandled rejection: ${e?.message || e}`));

const beat = setInterval(() => send({ heartbeat: { ts: Date.now() } }), 10000);
send({ hello: { pid: process.pid } });
